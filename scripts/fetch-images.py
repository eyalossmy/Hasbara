"""Download the site's photos and logos from Wikimedia, with their credits.

Reads scripts/images.json ({key: {article | file, logo?}}), saves each image to public/img/<key>.<ext>
and writes src/data/images.ts. Already fetched keys are kept in scripts/images.lock.json.
Run with: python scripts/fetch-images.py [key ...]   (keys force a refetch)
"""
import io, json, os, re, sys, time, urllib.error, urllib.parse, urllib.request

UA = 'HasbaraSiteBuilder/1.0 (https://github.com/eyalossmy/Hasbara) python-urllib'
OUT = 'public/img'
LOCK = 'scripts/images.lock.json'


def get(url, tries=8):
    for i in range(tries):
        try:
            return urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA}), timeout=40).read()
        except urllib.error.HTTPError as e:
            if e.code == 429:
                time.sleep(6 * (i + 1))
                continue
            raise
    raise RuntimeError('rate limited: ' + url)


def api(params):
    q = urllib.parse.urlencode({**params, 'format': 'json', 'redirects': 1})
    time.sleep(1.2)
    return json.loads(get('https://en.wikipedia.org/w/api.php?' + q))


def plain(html):
    text = re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', html or '')).strip()
    half = len(text) // 2
    return text[:half].strip() if len(text) % 2 == 0 and text[:half] == text[half:] else text


def resolve(entry):
    name = entry.get('file')
    if not name:
        r = api({'action': 'query', 'titles': entry['article'], 'prop': 'pageimages', 'piprop': 'name', 'pilicense': 'any'})
        page = next(iter(r['query']['pages'].values()))
        if 'pageimage' not in page:
            return None
        name = 'File:' + page['pageimage']
    r = api({'action': 'query', 'titles': name, 'prop': 'imageinfo', 'iiprop': 'url|extmetadata', 'iiurlwidth': 800})
    page = next(iter(r['query']['pages'].values()))
    if 'imageinfo' not in page:
        return None
    info = page['imageinfo'][0]
    meta = info.get('extmetadata', {})
    return {
        'url': info.get('thumburl') or info['url'],
        'page': info['descriptionurl'],
        'artist': plain(meta.get('Artist', {}).get('value'))[:60],
        'license': plain(meta.get('LicenseShortName', {}).get('value')),
    }


def main():
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
    manifest = json.load(open('scripts/images.json', encoding='utf-8'))
    only = set(sys.argv[1:])
    os.makedirs(OUT, exist_ok=True)
    done = json.load(open(LOCK, encoding='utf-8')) if os.path.exists(LOCK) else {}
    for v in done.values():
        v['artist'] = plain(v['artist'])
    for key, entry in manifest.items():
        if (only and key not in only) or (not only and key in done):
            continue
        try:
            info = resolve(entry)
        except Exception as e:  # one bad entry should not stop the rest
            print('failed:', key, e)
            continue
        if not info:
            print('no image:', key)
            continue
        ext = os.path.splitext(urllib.parse.urlparse(info['url']).path)[1].lower() or '.jpg'
        for old in [f for f in os.listdir(OUT) if f.startswith(key + '.')]:
            os.remove(os.path.join(OUT, old))
        open(os.path.join(OUT, key + ext), 'wb').write(get(info['url']))
        done[key] = {'src': f'/img/{key}{ext}', 'credit': info['page'], 'artist': info['artist'], 'license': info['license'], 'logo': bool(entry.get('logo'))}
        print('ok', key, info['license'])
        json.dump(done, open(LOCK, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    rows = '\n'.join(f'  {k}: {json.dumps(v, ensure_ascii=False)},' for k, v in done.items() if k in manifest)
    open('src/data/images.ts', 'w', encoding='utf-8').write(
        '// Generated by scripts/fetch-images.py from scripts/images.json. Every image links to its page on Wikimedia.\n'
        'export interface Pic { src: string; credit: string; artist: string; license: string; logo: boolean }\n\n'
        f'export const PICS = {{\n{rows}\n}} satisfies Record<string, Pic>\n\nexport type PicKey = keyof typeof PICS\n')


main()
